// 국내 학술지 삼선표(三線表): 상·하 굵은 가로선 + 머리행 아래 가는 선, 세로선 없음
const NONE = { style: BorderStyle.NONE, size: 0, color: 'FFFFFF' };
const THICK = { style: BorderStyle.SINGLE, size: 12, color: INK };
const THIN = { style: BorderStyle.SINGLE, size: 4, color: INK };
function TABLE(headers, rows, widths) {
  const total = widths.reduce((a, b) => a + b, 0);
  const scaled = widths.map(w => Math.round(w / total * CW));
  const lastIdx = rows.length - 1;
  const cell = (txt, { w, align, top = NONE, bottom = NONE, head = false }) =>
    new TableCell({
      borders: { top, bottom, left: NONE, right: NONE },
      width: { size: w, type: WidthType.DXA },
      margins: { top: 38, bottom: 38, left: 90, right: 90 },
      verticalAlign: VerticalAlign.CENTER,
      children: [new Paragraph({
        alignment: align,
        spacing: { line: 224 },
        children: [new TextRun({ text: txt, font: SERIF, size: 15, bold: head, color: INK })],
      })],
    });
  const headRow = new TableRow({
    tableHeader: true,
    children: headers.map((h, i) => cell(h, {
      w: scaled[i], align: AlignmentType.CENTER, head: true, top: THICK, bottom: THIN,
    })),
  });
  const bodyRows = rows.map((r, ri) => new TableRow({
    children: r.map((c, i) => cell(String(c), {
      w: scaled[i],
      align: i === 0 ? AlignmentType.LEFT : AlignmentType.CENTER,
      bottom: ri === lastIdx ? THICK : NONE,
    })),
  }));
  return new Table({
    width: { size: CW, type: WidthType.DXA },
    columnWidths: scaled,
    borders: { top: NONE, bottom: NONE, left: NONE, right: NONE,
      insideHorizontal: NONE, insideVertical: NONE },
    rows: [headRow, ...bodyRows],
  });
}

function CAPTION(text) {
  return new Paragraph({
    alignment: AlignmentType.CENTER,
    spacing: { before: 50, after: 110 },
    children: [new TextRun({ text, font: GOTHIC, size: 16, color: INK })],
  });
}

function FIG(file, caption, label) {
  const meta = { fig2_pipeline: [1250, 540], fig3_mar_hist: [640, 480], fig4_mar_map: [640, 480],
    fig5_icc_bar: [640, 480], fig6_nutrition_fitness: [1200, 500], fig8_ai_flow: [1250, 459] };
  const key = file.replace('.png', '');
  const [iw, ih] = meta[key];
  const wide = iw / ih > 1.2;
  const W = wide ? 440 : 330;
  const H = Math.round(W * ih / iw);
  return [
    new Paragraph({
      alignment: AlignmentType.CENTER,
      spacing: { before: 70, after: 30 },
      children: [new ImageRun({
        type: 'png',
        data: fs.readFileSync(path.join(FIGDIR, file)),
        transformation: { width: W, height: H },
        altText: { title: label, description: caption, name: label },
      })],
    }),
    CAPTION(`${label}  ${caption}`),
  ];
}

