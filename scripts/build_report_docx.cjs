// 인라인 **굵게** 파싱
function runs(text, base = {}) {
  const parts = text.split(/(\*\*[^*]+\*\*)/g).filter(Boolean);
  return parts.map(p => {
    if (p.startsWith('**') && p.endsWith('**')) {
      return new TextRun({ text: p.slice(2, -2), bold: true, font: SERIF, ...base });
    }
    return new TextRun({ text: p, font: SERIF, ...base });
  });
}

function P(text, opts = {}) {
  return new Paragraph({
    alignment: AlignmentType.JUSTIFIED,
    spacing: { line: 272, after: 96 },
    children: runs(text, opts.run || {}),
    ...opts.para,
  });
}

function H1(text) {
  return new Paragraph({
    heading: HeadingLevel.HEADING_1,
    spacing: { before: 240, after: 110 },
    children: [new TextRun({ text, bold: true, font: GOTHIC, size: 26, color: INK })],
  });
}
function H2(text) {
  return new Paragraph({
    heading: HeadingLevel.HEADING_2,
    spacing: { before: 170, after: 70 },
    children: [new TextRun({ text, bold: true, font: GOTHIC, size: 22, color: INK })],
  });
}

// 코드/수식 블록 (회색 음영 + 좌측 강조선)
function CODE(lines) {
  return lines.map((ln, i) =>
    new Paragraph({
      spacing: { line: 210, before: i === 0 ? 60 : 0, after: i === lines.length - 1 ? 110 : 0 },
      indent: { left: 240, right: 240 },
      shading: { type: ShadingType.CLEAR, fill: CODEFILL },
      border: {
        ...(i === 0 ? { top: { style: BorderStyle.SINGLE, size: 4, color: '999999', space: 3 } } : {}),
        left: { style: BorderStyle.SINGLE, size: 4, color: '999999', space: 6 },
        right: { style: BorderStyle.SINGLE, size: 4, color: '999999', space: 6 },
        ...(i === lines.length - 1 ? { bottom: { style: BorderStyle.SINGLE, size: 4, color: '999999', space: 3 } } : {}),
      },
      children: [new TextRun({ text: ln || ' ', font: MONO, size: 14, color: INK })],
    })
  );
}

